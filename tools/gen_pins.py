"""Generate main/kd_pins.h: the GPIO state the stock firmware leaves at its first superloop iteration,
from docs/stock_init.txt (tools/trace_init.py).  Our DOOM image replays it so every pin (the UI MCU's
link, its reset/boot lines, LED drivers, panel scan) is where the stock firmware puts it.

  python tools/gen_pins.py
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import kemu

PORTS = 'ABCDEFG'


def main():
    reg = {}                                   # (port, off) -> value
    odr = {p: 0 for p in PORTS}
    for line in open(os.path.join(kemu.REPO, 'docs', 'stock_init.txt')):
        m = re.search(r'GPIO([A-I])\+0x([0-9a-f]+)\s+0x[0-9a-f]+\s+= 0x([0-9a-f]+)', line)
        if not m:
            continue
        p, off, v = m.group(1), int(m.group(2), 16), int(m.group(3), 16)
        if p not in PORTS:
            continue
        if off == 0x14:
            odr[p] = v & 0xFFFF
        elif off == 0x18:
            if len(m.group(3)) <= 4:           # 16-bit store to BSRR low half: set
                odr[p] |= v
            else:
                odr[p] = (odr[p] | (v & 0xFFFF)) & ~(v >> 16)
        elif off == 0x1A:                      # 16-bit store to BSRR high half: reset
            odr[p] &= ~v
        else:
            reg[p, off] = v
    out = ['/* Generated by tools/gen_pins.py from docs/stock_init.txt: the stock GPIO state at its first',
           ' * superloop iteration.  {address, value}, applied in order: AF, type, speed, pull, output, mode. */',
           '#define KD_PINS_N %d', 'static const uint32_t kd_pins[][2] = {']
    n = 0
    for p in PORTS:
        base = 0x40020000 + 0x400 * PORTS.index(p)
        for off in (0x20, 0x24, 0x04, 0x08, 0x0C):
            if (p, off) in reg:
                out.append('    {0x%08X, 0x%08X},' % (base + off, reg[p, off])); n += 1
        out.append('    {0x%08X, 0x%08X},   /* GPIO%s ODR */' % (base + 0x14, odr[p], p)); n += 1
        if (p, 0x00) in reg:
            out.append('    {0x%08X, 0x%08X},   /* GPIO%s MODER */' % (base, reg[p, 0x00], p)); n += 1
    out.append('};')
    out[2] = out[2] % n
    path = os.path.join(kemu.REPO, 'main', 'kd_pins.h')
    with open(path, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('%d register writes -> main/kd_pins.h' % n)


if __name__ == '__main__':
    main()
