#!/usr/bin/env python3
"""
gen_tables.py - writes doom/source/kd_rtables.c: the view-size dependent
renderer tables for a 128x64 view (vanilla R_InitTextureMapping /
R_ExecuteSetViewSize maths with DOOM's own fixed point and finetangent).

Part of the KeyStep Pro DOOM port, GPLv2.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, "..", "source")
W, H = 128, 64
FRACBITS = 16
FRACUNIT = 1 << 16
FINEANGLES = 8192
ANGLETOFINESHIFT = 19
ANG90 = 0x40000000
FIELDOFVIEW = 2048


def s32(v):
    v &= 0xFFFFFFFF
    return v - (1 << 32) if v & 0x80000000 else v


def fixedmul(a, b):
    return s32((a * b) >> FRACBITS)


def fixeddiv(a, b):
    if (abs(a) >> 14) >= abs(b):
        return -0x80000000 if (a ^ b) < 0 else 0x7FFFFFFF
    # C: (int)(((int64)a << 16) / b), truncation toward zero
    q = abs(a << 16) // abs(b)
    return s32(q if (a < 0) == (b < 0) else -q)


def table(name):
    src = open(os.path.join(SRC, "tables.c")).read()
    m = re.search(name + r"\[\d+\]\s*=\s*\{(.*?)\}", src, re.S)
    return [int(x) for x in m.group(1).replace("\n", " ").split(",") if x.strip()]


finetangent = table("finetangent")
finesine = table("finesine")
finecosine = lambda i: finesine[i + FINEANGLES // 4]

centerx = W // 2
centerxfrac = centerx << FRACBITS
focallength = fixeddiv(centerxfrac, finetangent[FINEANGLES // 4 + FIELDOFVIEW // 2])
viewangletox = []
for i in range(FINEANGLES // 2):
    if finetangent[i] > FRACUNIT * 2:
        t = -1
    elif finetangent[i] < -FRACUNIT * 2:
        t = W + 1
    else:
        t = fixedmul(finetangent[i], focallength)
        t = (centerxfrac - t + FRACUNIT - 1) >> FRACBITS
        if t < -1:
            t = -1
        elif t > W + 1:
            t = W + 1
    viewangletox.append(t)
xtoviewangle = []
for x in range(W + 1):
    i = 0
    while viewangletox[i] > x:
        i += 1
    xtoviewangle.append(((i << ANGLETOFINESHIFT) - ANG90) & 0xFFFFFFFF)
for i in range(FINEANGLES // 2):
    if viewangletox[i] == -1:
        viewangletox[i] = 0
    elif viewangletox[i] == W + 1:
        viewangletox[i] = W
yslope = []
for i in range(H):
    dy = ((i - H // 2) << FRACBITS) + FRACUNIT // 2
    dy = abs(dy)
    yslope.append(fixeddiv((W // 2) * FRACUNIT, dy))
distscale = []
for i in range(W):
    cosadj = abs(finecosine(xtoviewangle[i] >> ANGLETOFINESHIFT))
    distscale.append(fixeddiv(FRACUNIT, cosadj))


def fmt(vals, per=16):
    lines = []
    for i in range(0, len(vals), per):
        lines.append("    " + ", ".join(str(v) for v in vals[i:i + per]) + ",")
    return "\n".join(lines)


out = []
out.append("/* kd_rtables.c - generated by converter/gen_tables.py for a %dx%d view. Do not edit. GPLv2. */" % (W, H))
out.append('#include "tables.h"')
out.append("const uint8_t viewangletox[%d] = {\n%s\n};" % (FINEANGLES // 2, fmt(viewangletox, 32)))
out.append("const angle_t xtoviewangle[%d] = {\n%s\n};" % (W + 1, fmt(["0x%08XU" % v for v in xtoviewangle], 8)))
out.append("const fixed_t yslope[%d] = {\n%s\n};" % (H, fmt(yslope, 8)))
out.append("const fixed_t distscale[%d] = {\n%s\n};" % (W, fmt(distscale, 8)))
open(os.path.join(SRC, "kd_rtables.c"), "w").write("\n".join(out) + "\n")
print("clipangle = 0x%08X, focallength = %d" % (xtoviewangle[0], focallength))

# vanilla light tables (R_InitLightTables / R_ExecuteSetViewSize), for the
# 320-wide vanilla projection; the renderer converts its scale to that.
LIGHTLEVELS, MAXLIGHTSCALE, MAXLIGHTZ, NUMCOLORMAPS = 16, 48, 128, 32
LIGHTZSHIFT, LIGHTSCALESHIFT, DISTMAP = 20, 12, 2
zl = []
sl = []
for i in range(LIGHTLEVELS):
    startmap = ((LIGHTLEVELS - 1 - i) * 2) * NUMCOLORMAPS // LIGHTLEVELS
    row = []
    for j in range(MAXLIGHTZ):
        scale = fixeddiv(160 * FRACUNIT, (j + 1) << LIGHTZSHIFT)
        scale >>= LIGHTSCALESHIFT
        level = startmap - scale // DISTMAP
        row.append(max(0, min(NUMCOLORMAPS - 1, level)))
    zl.append(row)
    row = []
    for j in range(MAXLIGHTSCALE):
        level = startmap - j * 320 // 320 // DISTMAP
        row.append(max(0, min(NUMCOLORMAPS - 1, level)))
    sl.append(row)
with open(os.path.join(SRC, "kd_rtables.c"), "a") as f:
    f.write("const uint8_t scalelight[%d][%d] = {\n%s\n};\n" % (LIGHTLEVELS, MAXLIGHTSCALE, "\n".join("    {" + ", ".join(map(str, r)) + "}," for r in sl)))
    f.write("const uint8_t zlight[%d][%d] = {\n%s\n};\n" % (LIGHTLEVELS, MAXLIGHTZ, "\n".join("    {" + ", ".join(map(str, r)) + "}," for r in zl)))

with open(os.path.join(SRC, "kd_rtables.c"), "a") as f:
    g = [int(round(255 * (i / 255.0) ** 0.7)) for i in range(256)]
    f.write("const uint8_t kd_gamma07[256] = {\n%s\n};\n" % fmt(g, 32))
